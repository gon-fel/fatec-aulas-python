# Descrição: Criar um programa que utilize a estrutura de repetição while para contar de 1 a 5.
# ==========================================

contador = 1 # controlador da repetição, com início em 1

while contador <= 5:
    
    print(contador)

    contador += 1 # Incrementa o contador em 1 a cada iteração do loop

print("Fim da contagem")